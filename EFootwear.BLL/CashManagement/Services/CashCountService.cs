using EFootwear.BLL.Abstractions;
using EFootwear.BLL.CashManagement.Abstractions;
using EFootwear.BLL.CashManagement.Contracts;
using EFootwear.BLL.Common;
using EFootwear.BLL.Core.Abstractions;
using EFootwear.Domain.CashManagement;
using EFootwear.Domain.Common;
using Microsoft.Extensions.Logging;

namespace EFootwear.BLL.CashManagement.Services;

/// <summary>
/// The Cash Calculator and View Cash Detail (docx 3.6, 3.7). The server computes the counted cash from the denominations, and the
/// expected cash from the books, so a client can never post a total of its own. The difference is generated by the database.
/// How Net Sale is calculated is not documented and is not decided here ([BUSINESS DECISION REQUIRED]); only the figures that
/// the schema can hold are stored.
/// </summary>
public sealed class CashCountService(
    ICashCountRepository cashCountRepository,
    IStoreRepository storeRepository,
    ICurrentUser currentUser,
    IUnitOfWork unitOfWork,
    ILogger<CashCountService> logger)
{
    public async Task<CashCountContextResponse> GetContextAsync(Guid storeId, DateOnly countDate, CancellationToken cancellationToken)
    {
        EnsureStoreAccess(storeId);
        var expectedCash = await cashCountRepository.GetExpectedCashAsync(storeId, countDate, cancellationToken);
        var existingCount = await cashCountRepository.FindByStoreAndDateAsync(storeId, countDate, cancellationToken);
        return new CashCountContextResponse(storeId, countDate, expectedCash, existingCount);
    }

    public Task<PagedResult<CashCountListItemResponse>> ListAsync(CashCountSearchRequest filter, PageRequest pageRequest, CancellationToken cancellationToken)
    {
        if (filter.StoreId is { } storeId) EnsureStoreAccess(storeId);
        if (filter.From is { } from && filter.To is { } to && from > to)
            throw new DomainException(ErrorKind.Validation, "The From date cannot be after the To date.");
        return cashCountRepository.ListAsync(filter, pageRequest.Normalized(), cancellationToken);
    }

    public async Task<CashCountResponse> SaveAsync(SaveCashCountRequest request, CancellationToken cancellationToken)
    {
        EnsureStoreAccess(request.StoreId);
        var usableStoreIds = await storeRepository.ActiveSellingStoreIdsAsync(currentUser.CompanyId, [request.StoreId], cancellationToken);
        if (usableStoreIds.Count != 1)
            throw new DomainException(ErrorKind.Validation, "Choose an active store of this company.");

        var countedCash = ValidateAndTotal(request);
        var expectedCash = await cashCountRepository.GetExpectedCashAsync(request.StoreId, request.CountDate, cancellationToken);
        var normalized = request with { Note = PromiseRules.NormalizeNote(request.Note) };

        var countId = await cashCountRepository.SaveAsync(normalized, countedCash, expectedCash, currentUser.UserId, cancellationToken);
        await unitOfWork.CommitAsync(cancellationToken);

        logger.LogInformation("Cash count {CountId} saved for store {StoreId} on {CountDate} in company {CompanyId} by user {UserId}",
            countId, request.StoreId, request.CountDate, currentUser.CompanyId, currentUser.UserId);
        return await cashCountRepository.FindByStoreAndDateAsync(request.StoreId, request.CountDate, cancellationToken)
               ?? throw new DomainException(ErrorKind.NotFound, "The cash count was not found after saving.");
    }

    /// <summary>Checks every figure and returns the total of the counted notes (whole rupees).</summary>
    private static long ValidateAndTotal(SaveCashCountRequest request)
    {
        if (request.OpeningCash < 0)
            throw new DomainException(ErrorKind.Validation, "The opening cash cannot be negative.");
        EnsureNotNegative(request.PaymentsAmount, "Payments");
        EnsureNotNegative(request.CreditSalesAmount, "Credit");
        EnsureNotNegative(request.CreditReceivedAmount, "Credit received");

        var seenDenominations = new HashSet<int>();
        foreach (var line in request.Denominations)
        {
            if (!CashDenominations.IsKnown(line.Denomination))
                throw new DomainException(ErrorKind.Validation,
                    $"{line.Denomination} is not a counted denomination ({string.Join(", ", CashDenominations.All)}).");
            if (line.NoteCount < 0)
                throw new DomainException(ErrorKind.Validation, "A note count cannot be negative.");
            if (!seenDenominations.Add(line.Denomination))
                throw new DomainException(ErrorKind.Validation, $"The denomination {line.Denomination} appears twice.");
        }
        return CashDenominations.TotalValue(request.Denominations.Select(line => (line.Denomination, line.NoteCount)));
    }

    private static void EnsureNotNegative(long? amount, string what)
    {
        if (amount is < 0)
            throw new DomainException(ErrorKind.Validation, $"{what} cannot be negative.");
    }

    private void EnsureStoreAccess(Guid storeId)
    {
        if (!currentUser.CanAccessStore(storeId))
            throw new DomainException(ErrorKind.Forbidden, "You do not have access to this store.");
    }
}
