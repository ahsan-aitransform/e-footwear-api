using System.Text;

namespace EFootwear.Domain.Security.Permissions;

/// <summary>
/// Writes the C# source of <c>PermissionCodes</c> from the catalog, so the constants and the catalog can never
/// disagree. The file is <c>Security/Permissions/PermissionCodes.generated.cs</c>. Regenerate it with
/// <c>dotnet run --project E-Footwear-Api -- generate-permission-codes</c>; a unit test fails when it is stale.
/// Shape: <c>PermissionCodes.Products.NewProduct.View</c> is the string "PRODUCTS.NEW_PRODUCT.VIEW".
/// </summary>
public static class PermissionCodesSourceGenerator
{
    public static string GenerateSource(IReadOnlyList<PermissionModuleDefinition> modules)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated>");
        source.AppendLine("// Generated from PermissionCatalogDefinitions. Do not edit by hand.");
        source.AppendLine("// Regenerate: dotnet run --project E-Footwear-Api -- generate-permission-codes");
        source.AppendLine("// </auto-generated>");
        source.AppendLine();
        source.AppendLine("namespace EFootwear.Domain.Security.Permissions;");
        source.AppendLine();
        source.AppendLine("/// <summary>Permission code constants for [RequirePermission] and role templates. One constant per catalog permission.</summary>");
        source.AppendLine("public static class PermissionCodes");
        source.AppendLine("{");
        foreach (var module in modules)
        {
            source.AppendLine($"    /// <summary>{Escape(module.DisplayName)}</summary>");
            source.AppendLine($"    public static class {ToPascalCase(module.ModuleCode)}");
            source.AppendLine("    {");
            foreach (var screen in module.Screens)
            {
                source.AppendLine($"        /// <summary>{Escape(screen.DisplayName)}</summary>");
                source.AppendLine($"        public static class {ToPascalCase(screen.ScreenCode)}");
                source.AppendLine("        {");
                foreach (var action in screen.Actions)
                    source.AppendLine($"            public const string {ToPascalCase(action.ActionCode)} = \"{action.PermissionCode}\";");
                source.AppendLine("        }");
            }
            source.AppendLine("    }");
        }
        source.AppendLine("}");
        return source.ToString().ReplaceLineEndings("\n");
    }

    /// <summary>STOCK_ADJUSTMENT_NON_ZERO_STOCK becomes StockAdjustmentNonZeroStock.</summary>
    public static string ToPascalCase(string upperSnakeCase) =>
        string.Concat(upperSnakeCase.Split('_', StringSplitOptions.RemoveEmptyEntries)
            .Select(word => char.ToUpperInvariant(word[0]) + word[1..].ToLowerInvariant()));

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
